# provenance.sh: classify every tracked file of tlsx by where it comes from
# and write PROVENANCE.md. Run it after every upstream sync.
#
#   scripts/provenance.sh            # write PROVENANCE.md
#   scripts/provenance.sh --check    # fail if PROVENANCE.md is out of date
#
# Classes:
#   (a) Go's file, unchanged or only mechanically rewritten: identical to the
#       file of the Go release in UPSTREAM.md after the rewrite of
#       upstream-lib.sh, ignoring //go:build lines and the one-line tlsx
#       notice under Go's header.
#   (b) Go's file with tlsx changes: the same path exists upstream and the
#       content differs; the count of differing lines is shown, and how many
#       of our lines carry a "// tlsx" marker.
#   (c) Written for tlsx, from CREDITS below: files that are not in Go.
#       Where a (c) file contains passages adapted from Go or data from a
#       standard, the notes column says so (from scripts/provenance-notes.tsv,
#       maintained by hand, and checked for existence here).
#   (d) Third-party material other than Go: listed in provenance-notes.tsv
#       with its source and licence. There is none today.
# Files not covered by any rule are reported as UNCLASSIFIED and make
# --check fail, so a new file cannot slip in without a decision.
set -euo pipefail

root="$(cd "$(dirname "$0")/.." && pwd)"
. "$root/scripts/upstream-lib.sh"
base="$(sed -n 's/^Base: *\(go[0-9.]*\).*/\1/p' "$root/UPSTREAM.md" | head -1)"
notes="$root/scripts/provenance-notes.tsv"
work="$(mktemp -d)"
echo "work directory: $work" >&2
extract "$(goroot "$base")" "$work/up"

# norm drops what the comparison ignores: //go:build lines (with the blank
# line after them) and tlsx's one-line notice under Go's header.
norm() {
	awk '/^\/\/go:build/ { skip = 1; next } skip && /^$/ { skip = 0; next } { skip = 0 } /^\/\/ Changes for tlsx: Copyright/ { next } { print }' "$1"
}

out="$work/PROVENANCE.md"
{
	echo "# Provenance"
	echo
	echo "Generated by \`scripts/provenance.sh\` against Go $base; do not edit."
	echo "Classes: (a) Go's file, unchanged or only mechanically rewritten;"
	echo "(b) Go's file with tlsx changes; (c) written for tlsx;"
	echo "(d) third-party material other than Go. See NOTICE for the licences."
	echo
	echo "| File | Class | Source | Notes |"
	echo "|---|---|---|---|"
} > "$out"

unclassified=0
cd "$root"
git ls-files --cached --others --exclude-standard | grep -v -e '^PROVENANCE.md$' | sort > "$work/files"
while IFS= read -r f; do
	note="$(awk -F'\t' -v f="$f" '$1 == f { print $3 }' "$notes")"
	note="${note#; }"
	cls="$(awk -F'\t' -v f="$f" '$1 == f { print $2 }' "$notes")"
	up="$work/up/$f"
	if [ -e "$up" ]; then
		gopath="$f"
		case "$f" in
		internal/tls12/*) gopath="crypto/internal/fips140/tls12/${f#internal/tls12/}" ;;
		internal/tls13/*) gopath="crypto/internal/fips140/tls13/${f#internal/tls13/}" ;;
		internal/bigmod/*) gopath="crypto/internal/fips140/bigmod/${f#internal/bigmod/}" ;;
		*) gopath="crypto/tls/$f" ;;
		esac
		if cmp -s <(norm "$f") <(norm "$up"); then
			echo "| \`$f\` | (a) | Go $base \`src/$gopath\` | ${note:-identical after the mechanical rewrite} |" >> "$out"
		else
			n="$(diff <(norm "$up") <(norm "$f") | grep -c '^[<>]' || true)"
			m="$(diff <(norm "$up") <(norm "$f") | grep -c '^>.*// tlsx' || true)"
			echo "| \`$f\` | (b) | Go $base \`src/$gopath\` | $n lines differ, $m of ours marked \`// tlsx\`${note:+; $note} |" >> "$out"
		fi
	elif [ -n "$cls" ]; then
		src="${note%%;*}"
		rest=""
		[ "$note" = "$src" ] || rest="${note#*; }"
		echo "| \`$f\` | $cls | $src | $rest |" >> "$out"
	else
		echo "| \`$f\` | UNCLASSIFIED | | add it to scripts/provenance-notes.tsv |" >> "$out"
		unclassified=$((unclassified + 1))
	fi
done < "$work/files"
# Every note must name an existing file.
while IFS=$'\t' read -r f _; do
	case "$f" in ''|'#'*) continue ;; esac
	[ -e "$root/$f" ] || { echo "provenance-notes.tsv names a missing file: $f" >&2; unclassified=$((unclassified + 1)); }
done < "$notes"

if [ "${1:-}" = "--check" ]; then
	if ! cmp -s "$out" "$root/PROVENANCE.md"; then
		diff -u "$root/PROVENANCE.md" "$out" || true
		echo "PROVENANCE.md is out of date: run scripts/provenance.sh" >&2
		exit 1
	fi
else
	cp "$out" "$root/PROVENANCE.md"
fi
[ "$unclassified" -eq 0 ] || { echo "$unclassified file(s) unclassified" >&2; exit 1; }
echo "PROVENANCE.md: $(grep -c '^| `' "$root/PROVENANCE.md") files" >&2
